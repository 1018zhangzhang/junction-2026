"use strict";
/* ============================================================================
 * 外语噪声拦截 · 回归测试
 * ----------------------------------------------------------------------------
 * 起因（2026-11-08 真机日志）：
 *   环境噪音被云端 SenseVoice 判成日语，返回「どうてですね。」，
 *   界面把它当成"听懂了"去执行，用户看到的是"听不懂话 + 屏幕冒日语"。
 * 修法：① 请求里 language 固定 zh（不再是 auto）；② 结果里假名/韩文占比过高就丢弃。
 * 这里只测 ②：validText 的判定，不碰网络。
 * ========================================================================== */

const { validText } = require("../src/asr.js");

let pass = 0, fail = 0;
function t(input, want, desc) {
  const got = validText(input);
  const ok = want === null ? got === null : got === want;
  if (ok) { pass++; console.log("ok   " + desc); }
  else { fail++; console.log("FAIL " + desc + "  期望 " + JSON.stringify(want) + " 实际 " + JSON.stringify(got)); }
}

// 该丢的
t("どうてですね。", null, "日语噪音（日志原文）");
t("これはなんですか", null, "整句日语");
t("안녕하세요", null, "韩语");
t("カチャカチャ", null, "拟声假名");
t("Okay.", null, "纯英文短噪声");
t("...", null, "只有标点");
t("", null, "空串");

// 该留的
t("麻婆豆腐", "麻婆豆腐", "菜名");
t("我想吃番茄炒蛋", "我想吃番茄炒蛋", "中文长句");
t("下一步", "下一步", "口令");
t("盐放多少", "盐放多少", "提问");
t("番茄豆腐", "番茄豆腐", "含形近字的菜名");
t("Yeah。我想吃可乐鸡翅。", "我想吃可乐鸡翅。", "英文噪声前缀要摘掉");
t("先放油，再放盐", "先放油，再放盐", "长句");
t("好的", "好的", "短应答");

// 中英混说不能被误杀
t("麻婆 tofu 豆腐", "麻婆 tofu 豆腐", "中英混说");

console.log("\n" + pass + "/" + (pass + fail) + " 通过" + (fail ? " · " + fail + " 失败" : ""));
process.exit(fail ? 1 : 0);
